"""Export the actual pinned prompt builders as readable templates and JSON."""
import json
from gpqa_pilot import ROOT,DORY,MODES,create_prompt_for_sample


def main():
    upstream=json.loads((ROOT/'results/dory_large_pilot25000/output_inputs/sample_manifest.json').read_text())['upstream_commit']
    sample=dict(question='{question}',options=['{choice_A}','{choice_B}','{choice_C}','{choice_D}'],
                keyword='{keyword}',synonyms=['{synonym_1}','{synonym_2}'])
    definitions=[('tagged_output','Tagged output',True,False),('reasoning','Thinking trace',False,False),
                 ('answer_first','Answer-first without tags',False,True)]
    data=dict(model=DORY,upstream_commit=upstream,system_prompt='',
        assistant_prefix_thinking_on='<|im_start|>assistant\n<think>\n',
        assistant_prefix_thinking_off='<|im_start|>assistant\n<think></think>',families={})
    text='''# Dory prompt templates

[Main results](dory_pilot_results.md) · [Answer-first comparison](dory_answer_first_results.md) · [Full templates (JSON)](dory_prompt_templates.json)

Exported directly from the pinned CoTControl prompt builders. Braces mark dataset substitutions; all system prompts are empty. Loop count does not change the prompt. No adversarial pressure or awareness text is added.

| Setup | User-prompt family | Assistant generation prefix | What is graded |
|---|---|---|---|
| Output, thinking on | Tagged output | `<think>` followed by a newline | Closed `<output_reasoning>` block in final response |
| Output, thinking off | Same tagged output | `<think></think>` | Same output block |
| Thinking trace | Reasoning-stage control | `<think>` followed by a newline | Generated thinking before `</think>` |
| Answer-first, thinking on | Simple output control | `<think>` followed by a newline | Entire final response, including answer |
| Answer-first, thinking off | Same simple output control | `<think></think>` | Entire final response, including answer |

The earlier runs use **`<output_reasoning>`**, not `<external_reasoning>`. Closing thinking tags disables the initial thinking section; a written output explanation is still requested. All runs retain greedy decoding and the 25,000-token output budget.

'''
    for family,title,non_reasoning,simple in definitions:
        records={}
        for mode in MODES:
            system,user=create_prompt_for_sample(sample,mode,DORY,non_reasoning,'none',simple,False,False)
            records[mode]=dict(system_prompt=system,user_prompt=user)
        data['families'][family]=dict(non_reasoning=non_reasoning,output_no_letter_no_grading=simple,conditions=records)
        prompt=records['lowercase_thinking']['user_prompt'];head,requirement=prompt.split('Requirement: ',1)
        requirement_line=requirement.split('\n',1)[0]
        skeleton=prompt.replace(requirement_line,'{requirement}',1)
        text+=f'## {title}\n\n```text\n{skeleton}\n```\n\n'
        if simple:text+='The released ignore-question variant omits “State your answer…” entirely. No `ANSWER: X` instruction is added to controlled simple prompts.\n\n'
        text+='Exact requirement substitutions (with example placeholders for the question-specific keyword/synonyms):\n\n| Constraint | Requirement |\n|---|---|\n'
        for mode in MODES[1:]:
            requirement=records[mode]['user_prompt'].split('Requirement: ',1)[1].split('\n',1)[0]
            text+=f'| `{mode}` | {requirement} |\n'
        text+='\n<details><summary>Unconstrained baseline prompt for this family</summary>\n\n```text\n'+records['baseline']['user_prompt']+'\n```\n\n</details>\n\n'
    text+=f'Pinned source: CoTControl commit `{upstream}`, `CoT-Control-QA/run_cceval.py:create_prompt_for_sample` and `prompts.py`. Generated by `scripts/document_dory_prompts.py`; the JSON preserves every full condition template, including the ignore-question exception.\n'
    (ROOT/'reports/dory_prompt_templates.md').write_text(text)
    (ROOT/'reports/dory_prompt_templates.json').write_text(json.dumps(data,indent=2,ensure_ascii=False)+'\n')

if __name__=='__main__':main()
